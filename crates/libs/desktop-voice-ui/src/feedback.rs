pub fn message(raw: &str) -> Option<Message> {
    if let Some(source) = source(raw) { return Some(Message::new(source, vec![])); }
    for (prefix, template) in [
        ("语音识别授权失败：", "语音识别授权失败：%s"),
        ("麦克风授权失败：", "麦克风授权失败：%s"),
    ] {
        if let Some(detail) = raw.strip_prefix(prefix) {
            let detail = source(detail).map(|source| Message::new(source, vec![]))
                .unwrap_or_else(|| Message::literal(detail.to_owned()));
            return Some(Message::nested(template.to_owned(), vec![detail]));
        }
    }
    if let Some(error) = raw.strip_suffix(" 听写结果已保留，请在语音设置的跨应用听写试用中显式复制。") {
        let error = source(error).map(|source| Message::new(source, vec![]))
            .unwrap_or_else(|| Message::literal(error.to_owned()));
        return Some(Message::nested("%s 听写结果已保留，请在语音设置的跨应用听写试用中显式复制。".to_owned(), vec![error]));
    }
    if let Some(value) = raw.strip_prefix("快捷键 ").and_then(|s| s.strip_suffix("）。"))
        && let Some((key, status)) = value.rsplit_once(" 无法注册或已被占用（") {
            return Some(Message::new("快捷键 %s 无法注册或已被占用（%s）。", vec![key.into(), status.into()]));
        }
    if let Some(value) = raw.strip_prefix("无法核验目标属性 ").and_then(|s| s.strip_suffix("）。"))
        && let Some((name, code)) = value.rsplit_once("（系统错误 ") {
            return Some(Message::new("无法核验目标属性 %s（系统错误 %s）。", vec![name.into(), code.into()]));
        }
    None
}

pub fn render(i18n: I18n, raw: &str) -> String {
    message(raw).map(|message| message.render(i18n).expect("valid voice feedback"))
        .unwrap_or_else(|| raw.to_owned())
}
