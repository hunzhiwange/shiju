//! Codex settings projected from the currently published managed catalog.
use super::{
    codex_classic::project_classic_tools,
    codex_review::apply_codex_auto_review_model,
    codex_subagent::plan_codex_subagent,
    model_ids::{Decoded, decode},
};
use crate::providers::live::{
    commit::{AppState, Mode},
    patch_toml::TomlPatch,
};
use serde_json::Value;
use vw_api_types::agent_apps::{AppId, aggregation::*};
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SettingsError {
    InvalidConfiguration,
    InvalidModel,
}
pub struct SettingsPlan {
    pub settings: CodexAggregationSettings,
    pub config: Vec<u8>,
    pub catalog: Option<Vec<u8>>,
}
/// The executor has authorized this project slot and captured these fixed files
/// under its physical write guard. Never follow a client catalog pointer.
pub fn plan(
    state: &AppState,
    config: Option<&[u8]>,
    published: Option<&[u8]>,
    requested: Option<&CodexSettingsValues>,
) -> Result<SettingsPlan, SettingsError> {
    use SettingsError::*;
    let previous = state.codex_aggregation_settings.clone().unwrap_or_default();
    let model_changed =
        requested.is_some_and(|value| value.subagent_model_id != previous.subagent_model_id);
    let mut intent = requested.cloned().unwrap_or(previous);
    if intent.subagent_model_id.is_none() {
        intent.subagent_effort = None;
    }
    let doc: toml_edit::DocumentMut = std::str::from_utf8(config.unwrap_or_default())
        .map_err(|_| InvalidConfiguration)?
        .parse()
        .map_err(|_| InvalidConfiguration)?;
    let attached = state.stack.enabled
        && state.mode.as_ref().is_some_and(|m| m.mode == Mode::Proxy && m.attached);
    let managed = attached
        && doc.get("model_catalog_json").and_then(|i| i.as_str())
            == Some(crate::providers::codex_catalog::CATALOG_FILENAME);
    let mut catalog: Option<Value> = if managed {
        Some(
            serde_json::from_slice(published.ok_or(InvalidConfiguration)?)
                .map_err(|_| InvalidConfiguration)?,
        )
    } else {
        None
    };
    let choice_catalog = catalog.clone();
    let mut sub = plan_codex_subagent(choice_catalog.as_ref(), intent.subagent_model_id.as_deref())
        .map_err(|_| InvalidConfiguration)?
        .with_effort(intent.subagent_effort);
    // A durable key alone is not current membership or publication authorization.
    sub.choices.retain(|choice| match decode(AppId::Codex, choice.model_id) {
        Ok(Decoded::Stack { key, .. }) => state.stack.keys.get(key).is_some_and(|id| {
            state.stack.members.contains(id)
                && state.mode.as_ref().and_then(|m| m.proxy_route.as_ref()) != Some(id)
        }),
        _ => false,
    });
    if !sub.choices.iter().any(|c| Some(c.model_id) == sub.effective_model_id) {
        sub.effective_model_id = None;
        sub.effective_effort = None;
    }
    if requested.is_some() {
        for id in [intent.subagent_model_id.as_deref(), intent.auto_review_model_id.as_deref()]
            .into_iter()
            .flatten()
        {
            if !sub.choices.iter().any(|c| c.model_id == id) {
                return Err(InvalidModel);
            }
        }
        // A model switch drops an unsupported old effort; an explicit invalid
        // effort for the current model is a rejected configuration request.
        if !model_changed
            && intent.subagent_effort.is_some()
            && sub.effective_effort != intent.subagent_effort
        {
            return Err(InvalidModel);
        }
        intent.subagent_effort = sub.effective_effort;
    }
    let choices = sub
        .choices
        .iter()
        .map(|c| CodexSettingsChoice {
            model_id: c.model_id.into(),
            label: c.label.into(),
            efforts: c.efforts.clone(),
        })
        .collect();
    let mut nested = Vec::new();
    sub.apply_to_nested(&mut nested);
    let patch = TomlPatch {
        set: nested.into_iter().map(|(p, v)| (p, toml_edit::Item::Value(v))).collect(),
        remove: vec![
            vec!["agents".into(), "default_subagent_model".into()],
            vec!["agents".into(), "default_subagent_reasoning_effort".into()],
        ],
        ..Default::default()
    };
    let projected_config = patch.apply(config).map_err(|_| InvalidConfiguration)?;
    let mut effective = CodexSettingsValues {
        subagent_model_id: sub.effective_model_id.map(str::to_owned),
        subagent_effort: sub.effective_effort,
        auto_review_model_id: None,
        classic_tools: false,
    };
    let ids: Vec<_> = sub.choices.iter().map(|c| c.model_id).collect();
    let cross = effective.subagent_model_id.is_some();
    let mut notices = Vec::new();
    // Third-party rows generated by codex_catalog have no native version override.
    // Remove our prior classic projection before applying the new preference.
    let classic = if let Some(catalog) = &mut catalog {
        let rows =
            catalog.get_mut("models").and_then(Value::as_array_mut).ok_or(InvalidConfiguration)?;
        let mut objects = rows
            .iter()
            .map(|v| v.as_object().cloned().ok_or(InvalidConfiguration))
            .collect::<Result<Vec<_>, _>>()?;
        for row in &mut objects {
            if row.get("multi_agent_version").and_then(Value::as_str) == Some("v1") {
                row.remove("multi_agent_version");
            }
        }
        let classic = project_classic_tools(Some(intent.classic_tools), &doc, cross, &mut objects);
        *rows = objects.into_iter().map(Value::Object).collect();
        effective.auto_review_model_id =
            apply_codex_auto_review_model(catalog, &ids, intent.auto_review_model_id.as_deref())
                .map_err(|_| InvalidConfiguration)?
                .map(str::to_owned);
        classic
    } else {
        project_classic_tools(Some(intent.classic_tools), &doc, false, &mut [])
    };
    effective.classic_tools = managed && classic.effective;
    if classic.multi_agent_v2_forced {
        notices.push(AggregationNotice::MultiAgentV2Forced);
    }
    if classic.encrypted_task_cross_provider {
        notices.push(AggregationNotice::EncryptedTaskCrossProvider);
    }
    if requested.is_some() && attached {
        notices.extend([
            AggregationNotice::NewSession,
            AggregationNotice::RestartDesktop,
            AggregationNotice::RestartEditor,
        ]);
    }
    if attached && !managed {
        notices.push(AggregationNotice::CodexRouteOwnsCatalog);
    }
    Ok(SettingsPlan {
        settings: CodexAggregationSettings {
            revision: String::new(),
            requested: intent,
            effective,
            choices,
            notices,
        },
        config: projected_config,
        catalog: catalog
            .map(|v| serde_json::to_vec_pretty(&v).map_err(|_| InvalidConfiguration))
            .transpose()?,
    })
}
