//! Native exit projection. The executor supplies saved profiles and the frozen
//! published projection under its authorized physical guard and revision check.
//! No backup store, runtime lifecycle or public request paths are introduced.
use crate::providers::{
    claude::ClaudeFile,
    codex_catalog::{CATALOG_FILENAME, CodexFiles},
    codex_login::{self, LoginInput},
    fields,
    live::{
        commit::*,
        patch_json::JsonPatch,
        patch_toml::TomlPatch,
        stage::{FileChange, WholeFile},
        write_guard::{AppWriteGuard, FilePrivacy, WriteError},
    },
    mode_state::{self, ClientConfiguration},
};
use serde_json::Value;
use std::{collections::BTreeSet, ffi::OsStr};
use vw_api_types::{agent_apps::AppId, id::ProjectScope};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RestoreError {
    Forbidden,
    RevisionConflict,
    RecoveryPending,
    UnsupportedTarget,
    InvalidConfiguration,
    TargetFailed,
}
impl From<WriteError> for RestoreError {
    fn from(error: WriteError) -> Self {
        match error {
            WriteError::Conflict => Self::RevisionConflict,
            WriteError::Recovered => Self::RecoveryPending,
            WriteError::InvalidResource => Self::InvalidConfiguration,
            WriteError::Io => Self::TargetFailed,
        }
    }
}
/// Trusted saved inputs, not HTTP payloads. `published` is the final native
/// projection generated by the existing publisher for the accepted revision.
pub struct Restore<'a> {
    pub project: &'a ProjectScope,
    pub expected: &'a AppState,
    pub published: &'a Value,
    pub direct: &'a Value,
}
fn authorize(
    tx: &ProviderTransactions,
    guard: &AppWriteGuard,
    input: &Restore<'_>,
    app: AppId,
) -> Result<(), RestoreError> {
    if guard.app() != app {
        return Err(RestoreError::UnsupportedTarget);
    }
    let state = tx.state(app)?;
    mode_state::observe(&state, input.project.tenant_scope())
        .map_err(|_| RestoreError::Forbidden)?;
    state.require_project(input.project).map_err(|_| RestoreError::Forbidden)?;
    if let Some(pending) = tx.pending(app)? {
        return Err(
            if pending.tenant != *input.project.tenant_scope()
                || pending.target.project_scope.as_ref() != Some(input.project)
            {
                RestoreError::Forbidden
            } else {
                RestoreError::RecoveryPending
            },
        );
    }
    if state != *input.expected {
        return Err(RestoreError::RevisionConflict);
    }
    if !state.stack.enabled
        || !state.mode.as_ref().is_some_and(|m| m.mode == Mode::Proxy && m.attached)
        || state.pointer.is_none()
    {
        return Err(RestoreError::InvalidConfiguration);
    }
    Ok(())
}
fn target(input: &Restore<'_>, contract: Contract) -> PendingTarget {
    let mut stack = input.expected.stack.clone();
    stack.enabled = false;
    PendingTarget {
        stack: Some(stack),
        mode: Some(ModeState {
            mode: Mode::Direct,
            attached: false,
            proxy_route: input.expected.mode.as_ref().and_then(|m| m.proxy_route.clone()),
            contract: Some(contract),
        }),
        ..Default::default()
    }
}
fn unchanged_check(
    tx: &ProviderTransactions,
    app: AppId,
    input: &Restore<'_>,
    unchanged: &impl Fn() -> bool,
) -> Result<(), WriteError> {
    if unchanged() && tx.state(app)? == *input.expected {
        Ok(())
    } else {
        Err(WriteError::Conflict)
    }
}
fn value_at<'a>(value: &'a Value, path: &[String]) -> Option<&'a Value> {
    path.iter().try_fold(value, |v, k| v.get(k))
}
// Only overwrite our unchanged publication (or an already restored value).
fn check_value(
    live: Option<&Value>,
    published: Option<&Value>,
    direct: Option<&Value>,
) -> Result<bool, RestoreError> {
    if published == direct || live == direct {
        return Ok(false);
    }
    if live != published {
        return Err(RestoreError::RevisionConflict);
    }
    Ok(true)
}

pub fn restore_claude(
    file: &mut ClaudeFile,
    tx: &ProviderTransactions,
    input: Restore<'_>,
    unchanged: impl Fn() -> bool,
) -> Result<(), RestoreError> {
    authorize(tx, &file.guard, &input, AppId::Claude)?;
    // Aggregation never switches Claude native login. Keep its account reference
    // and credential files intact; pending account transactions block the exit.
    if crate::providers::claude_login::configuration_has_pending_login(&file.guard)? {
        return Err(RestoreError::RecoveryPending);
    }
    unchanged_check(tx, AppId::Claude, &input, &unchanged)?;
    let contract = ClientConfiguration::saved(AppId::Claude, input.direct, false)
        .map_err(|_| RestoreError::InvalidConfiguration)?
        .contract();
    let before = file.guard.read(OsStr::new(file.name))?;
    let live = crate::providers::live::patch_json::object_value(before.as_deref().unwrap_or(b"{}"))
        .map_err(|_| RestoreError::InvalidConfiguration)?;
    let mut patch = JsonPatch::default();
    for document in [input.published, input.direct] {
        if !document.is_object() || !document.get("env").is_some_and(Value::is_object) {
            return Err(RestoreError::InvalidConfiguration);
        }
    }
    let top = input
        .published
        .as_object()
        .unwrap()
        .keys()
        .chain(input.direct.as_object().unwrap().keys())
        .filter(|k| fields::claude_floor_top(k))
        .cloned()
        .collect::<BTreeSet<_>>();
    let env = input.published["env"]
        .as_object()
        .unwrap()
        .keys()
        .chain(input.direct["env"].as_object().unwrap().keys())
        .filter(|k| fields::claude_floor_env(k) || fields::claude_exclusive_env(k))
        .cloned()
        .collect::<BTreeSet<_>>();
    for path in
        top.into_iter().map(|k| vec![k]).chain(env.into_iter().map(|k| vec!["env".into(), k]))
    {
        if check_value(
            value_at(&live, &path),
            value_at(input.published, &path),
            value_at(input.direct, &path),
        )? {
            if let Some(value) = value_at(input.direct, &path) {
                patch.set.push((path, value.clone()));
            } else {
                patch.remove.push(path);
            }
        }
    }
    let after = patch.apply(before.as_deref()).map_err(|_| RestoreError::InvalidConfiguration)?;
    let write = WholeFile::new(before.as_deref(), Some(after));
    tx.commit_project_checked(
        input.project,
        &mut file.guard,
        input.expected,
        false,
        &[FileChange { name: OsStr::new(file.name), privacy: FilePrivacy::Private, patch: &write }],
        target(&input, contract),
        || unchanged_check(tx, AppId::Claude, &input, &unchanged),
    )?;
    Ok(())
}

/// Restore config/catalog and native login in ONE original transaction. Login
/// material comes exclusively from the account owner's authorized LoginInput.
/// `catalog` is the saved direct catalog projection, not the aggregate catalog.
pub fn restore_codex(
    files: &mut CodexFiles,
    tx: &ProviderTransactions,
    input: Restore<'_>,
    login: LoginInput<'_>,
    catalog: Option<&vw_api_types::model_catalog::SavedCodexCatalog>,
    unchanged: impl Fn() -> bool,
) -> Result<(), RestoreError> {
    authorize(tx, &files.guard, &input, AppId::Codex)?;
    unchanged_check(tx, AppId::Codex, &input, &unchanged)?;
    let before = files.guard.read(OsStr::new("config.toml"))?;
    let live = std::str::from_utf8(before.as_deref().unwrap_or_default())
        .map_err(|_| RestoreError::InvalidConfiguration)?;
    let live_doc: toml_edit::DocumentMut =
        live.parse().map_err(|_| RestoreError::InvalidConfiguration)?;
    if live_doc.get("cli_auth_credentials_store").is_some_and(|v| v.as_str() != Some("file")) {
        return Err(RestoreError::UnsupportedTarget);
    }
    let login = codex_login::prepare(&files.guard, login)?;
    let projected = crate::providers::codex::project("", input.direct, None, login.login_on_disk)
        .map_err(|_| RestoreError::InvalidConfiguration)?;
    let mut desired: toml_edit::DocumentMut =
        projected.config().parse().map_err(|_| RestoreError::InvalidConfiguration)?;
    let direct_catalog =
        crate::models::codex_projection(catalog).map_err(|_| RestoreError::InvalidConfiguration)?;
    if direct_catalog.is_some() && desired.get("model_catalog_json").is_none() {
        desired.insert("model_catalog_json", toml_edit::value(CATALOG_FILENAME));
    }
    let published = input
        .published
        .get("config")
        .and_then(Value::as_str)
        .ok_or(RestoreError::InvalidConfiguration)?;
    let old: Value = toml::from_str(published).map_err(|_| RestoreError::InvalidConfiguration)?;
    let current: Value = toml::from_str(live).map_err(|_| RestoreError::InvalidConfiguration)?;
    let direct: Value =
        toml::from_str(&desired.to_string()).map_err(|_| RestoreError::InvalidConfiguration)?;
    let mut paths = fields::CODEX_FLOOR_TOP
        .iter()
        .chain(fields::CODEX_EXCLUSIVE_TOP)
        .map(|k| vec![(*k).to_owned()])
        .collect::<Vec<_>>();
    paths.extend(
        fields::CODEX_FLOOR_NESTED.iter().map(|p| p.iter().map(|k| (*k).to_owned()).collect()),
    );
    paths.push(vec!["model_providers".into(), "custom".into()]);
    let mut patch = TomlPatch::default();
    for path in paths {
        if check_value(value_at(&current, &path), value_at(&old, &path), value_at(&direct, &path))?
        {
            if value_at(&direct, &path).is_some() {
                let item = path
                    .iter()
                    .try_fold(desired.as_item(), |i, k| i.get(k))
                    .ok_or(RestoreError::InvalidConfiguration)?;
                patch.set.push((path, item.clone()));
            } else {
                patch.remove.push(path);
            }
        }
    }
    let config = patch.apply(before.as_deref()).map_err(|_| RestoreError::InvalidConfiguration)?;
    let config_write = WholeFile::new(before.as_deref(), Some(config));
    // Never touch a catalog after a user has changed its pointer. The config
    // three-way check above fails first for any such edit.
    let old_catalog = files.guard.read(OsStr::new(CATALOG_FILENAME))?;
    let managed = old.get("model_catalog_json").and_then(Value::as_str) == Some(CATALOG_FILENAME);
    if managed {
        let actual: Value =
            serde_json::from_slice(old_catalog.as_deref().ok_or(RestoreError::RevisionConflict)?)
                .map_err(|_| RestoreError::InvalidConfiguration)?;
        if input.published.get("catalog") != Some(&actual) {
            return Err(RestoreError::RevisionConflict);
        }
    }
    let publish_catalog = managed
        || desired.get("model_catalog_json").and_then(toml_edit::Item::as_str)
            == Some(CATALOG_FILENAME)
            && direct_catalog.is_some();
    if !managed && publish_catalog && old_catalog.is_some() && old_catalog != direct_catalog {
        return Err(RestoreError::RevisionConflict);
    }
    let catalog_write = WholeFile::new(old_catalog.as_deref(), direct_catalog);
    let mut changes = login.changes().into_iter().collect::<Vec<_>>();
    changes.push(FileChange {
        name: OsStr::new("config.toml"),
        privacy: FilePrivacy::Private,
        patch: &config_write,
    });
    if publish_catalog {
        changes.push(FileChange {
            name: OsStr::new(CATALOG_FILENAME),
            privacy: FilePrivacy::Private,
            patch: &catalog_write,
        });
    }
    let exclusive = fields::CODEX_EXCLUSIVE_TOP
        .iter()
        .filter_map(|k| direct.get(*k).map(|v| ((*k).into(), v.clone())))
        .collect();
    let contract = Contract {
        version: 1,
        key: input.expected.pointer.as_ref().unwrap().id.clone(),
        exclusive,
        claude_login_operation: None,
    };
    tx.commit_project_checked(
        input.project,
        &mut files.guard,
        input.expected,
        false,
        &changes,
        target(&input, contract),
        || unchanged_check(tx, AppId::Codex, &input, &unchanged),
    )?;
    Ok(())
}
