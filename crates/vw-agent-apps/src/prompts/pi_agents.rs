//! Pi instruction selection is derived from exact AGENTS.md bytes and catalog order.
use vw_api_types::agent_apps::{AppId, PromptEntry};

/// The first identical entry in persisted order owns the current file. Missing
/// and empty files differ; persisted enabled flags never participate.
pub fn active_id<'a>(entries: &'a [PromptEntry], live: Option<&str>) -> Option<&'a str> {
    let content = live?;
    entries.iter().find(|entry| entry.app_id == AppId::Pi && entry.content == content)
        .map(|entry| entry.id.as_str())
}

pub fn project(entries: &mut [PromptEntry], live: Option<&str>) {
    let selected = active_id(entries, live).map(str::to_owned);
    for entry in entries {
        entry.enabled = entry.app_id == AppId::Pi && selected.as_deref() == Some(entry.id.as_str());
    }
}

#[cfg(target_os = "macos")]
mod native {
    use super::*;
    use std::ffi::OsStr;
    use crate::providers::live::{
        commit::{PendingTarget, ProviderTransactions},
        stage::{FileChange, WholeFile},
        write_guard::{AppWriteGuard, FilePrivacy, WriteError},
    };
    use vw_api_types::TenantScope;

    pub enum Change {
        /// Existing-entry edit. Updating a disabled duplicate never writes the file.
        Edit(PromptEntry),
        Activate(String),
        Deactivate(String),
        Delete(String),
    }

    #[derive(Debug, PartialEq, Eq)]
    pub enum PiAgentsError {
        File(WriteError),
        Store(WriteError),
        Rollback { store: WriteError, file: WriteError },
    }
    impl From<WriteError> for PiAgentsError {
        fn from(error: WriteError) -> Self { Self::File(error) }
    }

    /// Hold the authorized Pi app guard across catalog read and this operation.
    /// `expected` must be the executor snapshot associated with the client's
    /// expected file revision, never newly read bytes substituted for a stale one.
    /// Preflight rechecks tenant/host authorization, catalog revisions and any
    /// required backup. commit_store atomically saves the supplied catalog (all
    /// enabled flags cleared), leaving storage unchanged on failure. Entry
    /// revisions/timestamps are generated by that storage adapter.
    #[allow(clippy::too_many_arguments)]
    pub fn apply<T>(
        guard: &mut AppWriteGuard,
        transactions: &ProviderTransactions,
        tenant: &TenantScope,
        entries: &[PromptEntry],
        expected: Option<&str>,
        change: Change,
        preflight: impl Fn() -> Result<(), WriteError>,
        commit_store: impl FnOnce(Vec<PromptEntry>) -> Result<T, WriteError>,
    ) -> Result<T, PiAgentsError> {
        if guard.app() != AppId::Pi || entries.iter().any(|e| e.app_id != AppId::Pi) {
            return Err(WriteError::InvalidResource.into());
        }
        let id = match &change {
            Change::Edit(entry) => &entry.id,
            Change::Activate(id) | Change::Deactivate(id) | Change::Delete(id) => id,
        };
        let index = entries.iter().position(|e| &e.id == id).ok_or(WriteError::InvalidResource)?;
        if entries.iter().filter(|e| &e.id == id).count() != 1 {
            return Err(WriteError::InvalidResource.into());
        }
        let owns_file = active_id(entries, expected) == Some(id.as_str());
        let mut catalog = entries.to_vec();
        let after = match change {
            Change::Edit(entry) => {
                if entry.app_id != AppId::Pi || entry.revision != entries[index].revision {
                    return Err(WriteError::Conflict.into());
                }
                let after = if owns_file { Some(entry.content.clone()) } else { expected.map(str::to_owned) };
                catalog[index] = entry;
                after
            }
            Change::Activate(_) => Some(entries[index].content.clone()),
            Change::Deactivate(_) => if owns_file { None } else { expected.map(str::to_owned) },
            Change::Delete(_) => {
                if owns_file { return Err(WriteError::Conflict.into()); }
                catalog.remove(index);
                expected.map(str::to_owned)
            }
        };
        for entry in &mut catalog { entry.enabled = false; }
        // Even a catalog-only edit compares the snapshot before persisting.
        publish(guard, transactions, tenant, expected.map(str::as_bytes), after.as_deref().map(str::as_bytes), preflight)?;
        match commit_store(catalog) {
            Ok(value) => Ok(value),
            Err(store) => {
                if after.as_deref() != expected {
                    publish(guard, transactions, tenant, after.as_deref().map(str::as_bytes), expected.map(str::as_bytes), || Ok(()))
                        .map_err(|file| PiAgentsError::Rollback { store, file })?;
                }
                Err(PiAgentsError::Store(store))
            }
        }
    }

    fn publish(
        guard: &mut AppWriteGuard,
        transactions: &ProviderTransactions,
        tenant: &TenantScope,
        expected: Option<&[u8]>,
        after: Option<&[u8]>,
        preflight: impl Fn() -> Result<(), WriteError>,
    ) -> Result<(), WriteError> {
        let patch = WholeFile::new(expected, after.map(<[u8]>::to_vec));
        transactions.commit_checked(tenant, guard, &[FileChange {
            name: OsStr::new("AGENTS.md"), privacy: FilePrivacy::Private, patch: &patch,
        }], PendingTarget::default(), preflight)
    }
}
#[cfg(target_os = "macos")]
pub use native::{Change, PiAgentsError, apply};
