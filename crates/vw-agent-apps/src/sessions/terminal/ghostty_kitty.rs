//! Ghostty and Kitty attach to a host-owned PTY without receiving CLI credentials.
use crate::apps::launch::{request::LaunchMaterial, terminal_session::TerminalSession};
use crate::sessions::resume::ResumePlan;
use std::{
    path::{Path, PathBuf},
    process::{Command, Stdio},
};
use vw_api_types::external_session::ExternalSessionIdentity;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Terminal {
    Ghostty,
    Kitty,
}

/// Run on the authorized execution host with a freshly rebuilt plan, retaining
/// its authorization guard until the native CLI and PTY resources are reaped.
pub fn launch_resume(
    plan: &ResumePlan,
    terminal: Terminal,
    resolve_agy: impl FnOnce(&ExternalSessionIdentity, &mut Command) -> Result<(), String>,
) -> Result<(), String> {
    let mut command = plan.command_with_credentials(resolve_agy)?;
    let home = command
        .get_envs()
        .find(|(key, _)| *key == "HOME")
        .and_then(|(_, value)| value)
        .map(PathBuf::from)
        .ok_or("resume execution home is missing")?;
    let app = application(terminal, &home)?;
    let session = TerminalSession::connect_with(Path::new("/tmp"), |_, material| {
        launch_attachment(terminal, &app, &home, material)
    })?;
    let status = session.run(&mut command, || {}).map_err(|_| "native resume process failed")?;
    if !status.success() {
        return Err(format!("native resume process exited unsuccessfully ({status})"));
    }
    Ok(())
}

fn application(terminal: Terminal, home: &Path) -> Result<PathBuf, String> {
    let name = match terminal {
        Terminal::Ghostty => "Ghostty.app",
        Terminal::Kitty => "kitty.app",
    };
    [Path::new("/Applications").join(name), home.join("Applications").join(name)]
        .into_iter()
        .find(|path| path.is_dir())
        .ok_or_else(|| match terminal {
            Terminal::Ghostty => "Ghostty is not installed".into(),
            Terminal::Kitty => "Kitty is not installed".into(),
        })
}

fn launch_attachment(
    terminal: Terminal,
    app: &Path,
    home: &Path,
    material: &LaunchMaterial,
) -> Result<(), String> {
    // Material is generated by TerminalSession, never supplied by a request.
    // Keep every path as one argv item, including spaces, quotes and Chinese.
    let mut open = Command::new("/usr/bin/open");
    open.env_clear()
        .env("HOME", home)
        .env("PATH", "/usr/bin:/bin:/usr/sbin:/sbin")
        .current_dir(&material.cwd)
        .arg("-na")
        .arg(app)
        .arg("--args");
    match terminal {
        Terminal::Ghostty => {
            let cwd = material
                .cwd
                .to_str()
                .filter(|value| {
                    material.cwd.is_absolute() && !value.chars().any(char::is_control)
                })
                .ok_or("invalid terminal attachment directory")?;
            open.arg("--quit-after-last-window-closed=true")
                .arg(format!("--working-directory={cwd}"));
        }
        Terminal::Kitty => {
            open.arg("--directory").arg(&material.cwd);
        }
    }
    // The shell interprets only TerminalSession's private script; native resume
    // argv/cwd/env and AGY credentials stay in the host-side Command above.
    let status = open
        .arg("-e")
        .arg(&material.program)
        .args(&material.args)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map_err(|_| match terminal {
            Terminal::Ghostty => "cannot launch Ghostty",
            Terminal::Kitty => "cannot launch Kitty",
        })?;
    if !status.success() {
        return Err(match terminal {
            Terminal::Ghostty => format!("Ghostty launch failed ({status})"),
            Terminal::Kitty => format!("Kitty launch failed ({status})"),
        });
    }
    Ok(())
}
