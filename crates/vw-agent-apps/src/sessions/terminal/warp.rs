//! Warp attaches to a host-owned PTY without receiving native CLI credentials.
use crate::apps::launch::{request::LaunchMaterial, terminal_session::TerminalSession};
use crate::sessions::resume::ResumePlan;
use std::{
    path::{Path, PathBuf},
    process::{Command, Stdio},
};
use vw_api_types::external_session::ExternalSessionIdentity;

/// Run on the authorized execution host with a freshly rebuilt plan, retaining
/// its authorization guard until the native CLI and PTY resources are reaped.
pub fn launch_resume(
    plan: &ResumePlan,
    resolve_agy: impl FnOnce(&ExternalSessionIdentity, &mut Command) -> Result<(), String>,
) -> Result<(), String> {
    let mut command = plan.command_with_credentials(resolve_agy)?;
    let home = command
        .get_envs()
        .find(|(key, _)| *key == "HOME")
        .and_then(|(_, value)| value)
        .map(PathBuf::from)
        .ok_or("resume execution home is missing")?;
    let app = [PathBuf::from("/Applications/Warp.app"), home.join("Applications/Warp.app")]
        .into_iter()
        .find(|path| path.is_dir())
        .ok_or("Warp is not installed in the supported locations")?;
    let session = TerminalSession::connect_with(Path::new("/tmp"), |_, material| {
        launch_attachment(&app, &home, material)
    })?;
    let status = session.run(&mut command, || {}).map_err(|_| "native resume process failed")?;
    if !status.success() {
        return Err(format!("native resume process exited unsuccessfully ({status})"));
    }
    Ok(())
}

fn launch_attachment(app: &Path, home: &Path, material: &LaunchMaterial) -> Result<(), String> {
    // Warp executes the path supplied by its native URL protocol. This is the
    // private executable script generated by TerminalSession, never a native
    // resume command or a client-supplied path. The session owns its cleanup on
    // launch failure, attachment timeout and normal process completion.
    if material.program != Path::new("/bin/sh") || material.args.len() != 1 {
        return Err("invalid Warp attachment material".into());
    }
    let script = Path::new(&material.args[0]);
    if !script.is_absolute()
        || script.parent() != Some(material.cwd.as_path())
        || material.args[0].chars().any(char::is_control)
    {
        return Err("invalid Warp attachment path".into());
    }
    let encoded = material.args[0].bytes().map(|byte| format!("%{byte:02X}")).collect::<String>();
    let url = format!("warp://action/new_tab?path={encoded}");
    let status = Command::new("/usr/bin/open")
        .env_clear()
        .env("HOME", home)
        .env("PATH", "/usr/bin:/bin:/usr/sbin:/sbin")
        .current_dir(&material.cwd)
        .arg("-a")
        .arg(app)
        .arg(url)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map_err(|_| "cannot launch Warp")?;
    if !status.success() {
        return Err(format!("Warp launch failed ({status})"));
    }
    Ok(())
}
