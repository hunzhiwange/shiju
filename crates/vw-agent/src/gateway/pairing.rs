//! # 配对端点处理模块
//!
//! 本模块提供网关的设备配对功能，允许新客户端通过一次性配对码获取
//! 长期有效的 Bearer 认证令牌。
//!
//! ## 核心功能
//!
//! - **配对验证**：验证客户端提交的一次性配对码
//! - **令牌颁发**：成功配对后颁发持久化 Bearer 令牌
//! - **速率限制**：防止配对端点被滥用
//! - **令牌持久化**：将配对令牌保存到配置文件
//!
//! ## 安全考虑
//!
//! - 配对码具有时效性和一次性特性
//! - 实施严格的速率限制防止暴力破解
//! - 失败次数过多会触发锁定机制
//! - 令牌持久化失败不影响当前会话使用

pub use agent_gateway::pairing::{handle_pair, handle_pair_code, persist_pairing_tokens};
