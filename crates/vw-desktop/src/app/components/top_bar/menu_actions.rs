//! topbar / 原生菜单共享的菜单动作 ID。

/// 菜单项稳定 ID，供 topbar 与 macOS 原生菜单共用。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum NativeMenuAction {
    FileNewSession,
    FileNewProject,
    FileShowSessions,
    FileShowProjects,
    FileSave,
    FileSaveAll,
    FileGoHome,
    EditUndo,
    EditRedo,
    EditCut,
    EditCopy,
    EditPaste,
    EditOpenSearch,
    EditOpenReplace,
    EditFindInProject,
    EditReplaceInProject,
    ViewToggleSettingsPanel,
    ViewToggleFileManager,
    ViewToggleFileManagerChanges,
    ViewToggleDiffPanel,
    ViewToggleTerminalPanel,
    ViewToggleWorkSidebar,
    ViewWorkOverview,
    ViewWorkWorkspaceFiles,
    ViewWorkBrowser,
    HelpAbout,
    HelpRestart,
    HelpInstallCli,
    HelpCheckUpdate,
}

#[cfg(any(target_os = "macos", test))]
impl NativeMenuAction {
    pub(crate) const fn id(self) -> &'static str {
        match self {
            Self::FileNewSession => "native.file.new_session",
            Self::FileNewProject => "native.file.new_project",
            Self::FileShowSessions => "native.file.show_sessions",
            Self::FileShowProjects => "native.file.show_projects",
            Self::FileSave => "native.file.save",
            Self::FileSaveAll => "native.file.save_all",
            Self::FileGoHome => "native.file.go_home",
            Self::EditUndo => "native.edit.undo",
            Self::EditRedo => "native.edit.redo",
            Self::EditCut => "native.edit.cut",
            Self::EditCopy => "native.edit.copy",
            Self::EditPaste => "native.edit.paste",
            Self::EditOpenSearch => "native.edit.open_search",
            Self::EditOpenReplace => "native.edit.open_replace",
            Self::EditFindInProject => "native.edit.find_in_project",
            Self::EditReplaceInProject => "native.edit.replace_in_project",
            Self::ViewToggleSettingsPanel => "native.view.toggle_settings_panel",
            Self::ViewToggleFileManager => "native.view.toggle_file_manager",
            Self::ViewToggleFileManagerChanges => "native.view.toggle_file_manager_changes",
            Self::ViewToggleDiffPanel => "native.view.toggle_diff_panel",
            Self::ViewToggleTerminalPanel => "native.view.toggle_terminal_panel",
            Self::ViewToggleWorkSidebar => "native.view.toggle_work_sidebar",
            Self::ViewWorkOverview => "native.view.work_overview",
            Self::ViewWorkWorkspaceFiles => "native.view.work_workspace_files",
            Self::ViewWorkBrowser => "native.view.work_browser",
            Self::HelpAbout => "native.help.about",
            Self::HelpRestart => "native.help.restart",
            Self::HelpInstallCli => "native.help.install_cli",
            Self::HelpCheckUpdate => "native.help.check_update",
        }
    }

    pub(crate) fn from_id(id: &str) -> Option<Self> {
        Some(match id {
            "native.file.new_session" => Self::FileNewSession,
            "native.file.new_project" => Self::FileNewProject,
            "native.file.show_sessions" => Self::FileShowSessions,
            "native.file.show_projects" => Self::FileShowProjects,
            "native.file.save" => Self::FileSave,
            "native.file.save_all" => Self::FileSaveAll,
            "native.file.go_home" => Self::FileGoHome,
            "native.edit.undo" => Self::EditUndo,
            "native.edit.redo" => Self::EditRedo,
            "native.edit.cut" => Self::EditCut,
            "native.edit.copy" => Self::EditCopy,
            "native.edit.paste" => Self::EditPaste,
            "native.edit.open_search" => Self::EditOpenSearch,
            "native.edit.open_replace" => Self::EditOpenReplace,
            "native.edit.find_in_project" => Self::EditFindInProject,
            "native.edit.replace_in_project" => Self::EditReplaceInProject,
            "native.view.toggle_settings_panel" => Self::ViewToggleSettingsPanel,
            "native.view.toggle_file_manager" => Self::ViewToggleFileManager,
            "native.view.toggle_file_manager_changes" => Self::ViewToggleFileManagerChanges,
            "native.view.toggle_diff_panel" => Self::ViewToggleDiffPanel,
            "native.view.toggle_terminal_panel" => Self::ViewToggleTerminalPanel,
            "native.view.toggle_work_sidebar" => Self::ViewToggleWorkSidebar,
            "native.view.work_overview" => Self::ViewWorkOverview,
            "native.view.work_workspace_files" => Self::ViewWorkWorkspaceFiles,
            "native.view.work_browser" => Self::ViewWorkBrowser,
            "native.help.about" => Self::HelpAbout,
            "native.help.restart" => Self::HelpRestart,
            "native.help.install_cli" => Self::HelpInstallCli,
            "native.help.check_update" => Self::HelpCheckUpdate,
            _ => return None,
        })
    }
}
