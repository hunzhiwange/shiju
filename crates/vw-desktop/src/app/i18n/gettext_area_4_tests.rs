use super::{I18n, settings_models::messages::Feedback};
use vw_config_types::ui::DesktopLocale;

#[test]
fn desktop_gettext_area_4_uses_chinese_keys() {
    let raw = "提供商/%n/{}";
    let feedback = Feedback::owned("service %s 失败: %s", vec!["restart".into(), raw.into()]);
    for (locale, label, expected) in [
        (DesktopLocale::SimplifiedChinese, "模型详情", "service restart 失败: "),
        (DesktopLocale::TraditionalChinese, "模型詳情", "service restart 失敗: "),
        (DesktopLocale::English, "Model details", "service restart failed: "),
    ] {
        assert_eq!(I18n::new(locale).__("模型详情"), label);
        assert_eq!(feedback.display(locale), format!("{expected}{raw}"));
    }
}

