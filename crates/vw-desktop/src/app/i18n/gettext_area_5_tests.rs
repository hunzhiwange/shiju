use super::{I18n, settings_runtime, settings_security};
use vw_config_types::ui::DesktopLocale;

#[test]
fn desktop_gettext_area_5_uses_chinese_keys() {
    let raw = "用户/%n/原始错误";
    for (locale, runtime, security) in [
        (DesktopLocale::SimplifiedChinese, "运行时类型", "安全配置"),
        (DesktopLocale::TraditionalChinese, "執行環境類型", "安全設定"),
        (DesktopLocale::English, "Runtime type", "Security configuration"),
    ] {
        assert_eq!(settings_runtime::text(locale, "运行时类型"), runtime);
        assert_eq!(I18n::new(locale).__("安全配置"), security);
        assert_eq!(settings_runtime::validation_error(locale, raw), raw);
        assert!(
            settings_runtime::validation_error(locale, &format!("列表项已存在：{raw}"))
                .ends_with(raw)
        );
        assert!(settings_runtime::observability_help(locale).contains("runtime_trace_mode"));
        assert!(settings_security::help(locale).contains("sandbox"));
    }
}

