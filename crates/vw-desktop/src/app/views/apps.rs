//! 应用列表视图模块
//!
//! 本模块负责渲染应用列表主界面，提供应用磁贴网格展示和模态框管理功能。
//! 该视图是 VibeWindow 的核心界面之一，用于展示和操作已集成的应用程序。
//!
//! # 主要功能
//!
//! - 渲染应用磁贴网格布局
//! - 管理和显示模态框（如应用详情、设置等）
//! - 处理模态框打开时的界面锁定状态
//!
//! # 架构
//!
//! 模块包含三个子模块：
//! - `modals`: 模态框管理，负责创建和管理弹出窗口
//! - `tiles`: 磁贴渲染，负责生成应用磁贴网格
//! - `ui`: UI 组件，提供通用界面元素

use crate::app::{App, Message};
use iced::Element;

mod modals;
mod tiles;
mod ui;

/// 渲染应用列表主视图
///
/// 生成完整的应用列表界面，包括头部、磁贴网格和可选的模态框层。
/// 当有模态框激活时，会在主内容上方显示半透明遮罩层。
///
/// # 参数
///
/// - `app`: 应用状态引用，包含所有需要渲染的数据
///
/// # 返回值
///
/// 返回 Iced 框架的 `Element`，代表完整的视图元素树
///
/// # 布局结构
///
/// ```text
/// ┌─────────────────────────────┐
/// │  Header (标题栏/工具栏)      │
/// ├─────────────────────────────┤
/// │                             │
/// │  Tiles Grid (应用磁贴网格)   │
/// │                             │
/// └─────────────────────────────┘
///
/// 当模态框激活时：
/// ┌─────────────────────────────┐
/// │  Base Content (半透明)      │
/// │  ┌───────────────────────┐  │
/// │  │  Modal Overlay        │  │
/// │  │  (半透明黑色遮罩)       │  │
/// │  └───────────────────────┘  │
/// │  ┌───────────────────────┐  │
/// │  │  Modal Layer          │  │
/// │  │  (居中的模态框内容)     │  │
/// │  └───────────────────────┘  │
/// └─────────────────────────────┘
/// ```
///
/// # 示例
///
/// ```rust,ignore
/// let element = view(&app);
/// // 返回可直接用于 Iced 渲染的元素
/// ```
pub fn view(app: &App) -> Element<'_, Message> {
    let active_modal = modals::active_modal(app);
    let blocked = active_modal.is_some();
    desktop_apps_ui::apps_view::view(tiles::render_header(app, blocked), tiles::render_tiles_grid(app, blocked), active_modal)
}

