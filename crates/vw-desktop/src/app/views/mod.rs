//! # 视图模块 (Views Module)
//!
//! 本模块提供了 VibeWindow 应用的所有视图组件和界面相关的功能。
//!
//! ## 模块职责
//!
//! - 组织和管理应用的用户界面视图
//! - 提供各类工具视图的统一入口
//! - 实现视图的模块化组织结构
//!
//! ## 子模块说明
//!
//! - [`apps`] - 应用管理视图
//! - [`home`] - 首页视图
//! - [`project`] - 项目管理视图
//! - [`task_board`] - 任务看板视图
//! - [`usage`] - 应用使用情况和统计视图
//!
//! ## 设计理念
//!
//! 本模块采用模块化设计，每个工具或功能都有独立的视图子模块，
//! 便于维护和扩展。新增工具视图时，只需创建新的子模块并在本文件中导出即可。

/// 应用管理视图模块
///
/// 提供应用程序的管理、配置和监控相关的视图组件。
pub mod apps;

#[cfg(not(target_arch = "wasm32"))]
pub(crate) mod expert_hub;

/// 首页视图模块
///
/// 应用的主页面视图，包含导航、快捷入口等核心界面元素。
pub mod home;

/// 知识库工作台视图模块
///
/// 提供知识库列表、文档管理与召回测试功能视图。
pub mod knowledge;

/// 项目视图模块
///
/// 提供项目信息的展示和管理相关视图。
pub mod project;

/// 任务看板视图模块
///
/// 提供任务的可视化看板界面，支持任务的状态管理和跟踪。
pub mod task_board;

/// 工作流管理面板视图模块
pub mod workflow_manager;

/// 使用情况视图模块
///
/// 提供应用使用统计、资源消耗监控等信息的展示视图。
pub mod usage;
